/**
 * Install source-only research instructions with no tools or runtime directory.
 * @param ctx - unpublished native Agent scope.
 */
export function applyResearchPolicy(ctx: Context): void {
  applyContentRules(ctx, RESEARCH_POLICY)
}

/**
 * Serialize fixed evidence and safe repair errors for the next native attempt.
 * @param input - immutable source-only input; no personal profile is inferred.
 * @param errors - errors from the completed previous attempt, if any.
 * @returns complete actual user prompt, retained in the native Session.
 */
export function researchPrompt(input: ResearchInputSnapshot, errors: readonly string[]): string {
  return (
    '<输入材料>\n' +
    JSON.stringify(input) +
    '\n</输入材料>\n' +
    (errors.length === 0 ? '' : '上次完整输出的校验错误，请依据同一原文修复：\n' + JSON.stringify(errors))
  )
}
