/** Complete employee deployment in Edge; content is explicitly supplied by a synthetic local model. */
import { chromium } from 'playwright'
import { expect, it } from 'vitest'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { EmployeeFixture, PASSWORD, contentReply } from '../../education-bundle/tests/employee-fixture.ts'
import type { SourceDTO } from '@deepseek-ai/dsh-experimental-education-platform/types'

const proof = fileURLToPath(new URL('../../../../.cache/education-employee-browser-proof', import.meta.url))
it('uses real employee login, profiles, imports, generation, local edits, Unicode selection, versions, revocation and account switching at 375px', async () => {
  mkdirSync(proof, { recursive: true })
  const fixture = await EmployeeFixture.create()
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined
  const errors: string[] = []
  try {
    await fixture.start()
    browser = await chromium.launch({ channel: process.env.EDUCATION_BROWSER_CHANNEL ?? 'msedge' })
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: 'en-US', acceptDownloads: true })
    const page = await context.newPage()
    page.on('pageerror', (error) => { errors.push(error.message) })
    await page.goto(fixture.origin)
    await page.getByLabel('Username', { exact: true }).fill('employee-a')
    await page.getByLabel('Password', { exact: true }).fill(PASSWORD)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    const panel = page.getByRole('region', { name: 'Writing workspace', exact: true })
    await panel.waitFor()
    await panel.getByText('My profile and sources', { exact: true }).click()
    await panel.getByLabel('Confirmed facts', { exact: true }).fill('这是合成测试。我是教培从业者，今天整理一次课堂观察。没有其他已确认经历。')
    await panel.getByLabel('Writing preferences', { exact: true }).fill('短句，自然，讲清一件事。')
    await panel.getByLabel('Prohibited promises', { exact: true }).fill('不承诺提分、业绩或升学结果。')
    await panel.getByRole('button', { name: 'Save profile version', exact: true }).click()
    await panel.getByText('Current profile version 1', { exact: true }).waitFor()
    await panel.getByLabel('Import TXT or Markdown text').setInputFiles({ name: 'approved.txt', mimeType: 'text/plain', buffer: Buffer.from('这是合成文本资料。课堂观察：先问学生如何理解题目，再讨论解法。') })
    await expect.poll(() => panel.getByLabel('Source text', { exact: true }).inputValue()).toContain('先问学生')
    await panel.getByRole('checkbox', { name: 'I confirm that I may use this source' }).check()
    await panel.getByRole('button', { name: 'Save source version', exact: true }).click()
    await panel.getByRole('button', { name: 'Revoke authorization', exact: true }).waitFor()
    await panel.getByText('My profile and sources', { exact: true }).click()
    await panel.getByLabel('Project name', { exact: true }).fill('Browser spoken project')
    await panel.getByRole('button', { name: 'New project', exact: true }).click()
    const editor = panel.getByRole('textbox', { name: 'Current draft', exact: true })
    await panel.getByRole('heading', { name: 'Browser spoken project', exact: true }).waitFor()
    const cookies = (await context.cookies()).map(cookie => `${cookie.name}=${cookie.value}`).join('; ')
    const sources = await fixture.rpc<readonly SourceDTO[]>(cookies, 'sourcesList', {})
    expect(sources).toHaveLength(1)
    await panel.getByRole('checkbox', { name: 'approved.txt', exact: true }).check()
    const firstBody = '开头😀\n只改这里\n结尾'
    fixture.upstream.script.push(contentReply(firstBody, [sources[0]!.versionId]))
    const instruction = panel.getByLabel('Writing or revision request', { exact: true })
    await instruction.fill('请只依据已确认事实写一条口播，不要编造经历。')
    await panel.getByRole('button', { name: 'Generate draft', exact: true }).click()
    await expect.poll(() => editor.inputValue(), { timeout: 15_000 }).toBe(firstBody)
    await panel.getByRole('button', { name: 'Save version', exact: true }).click()
    await panel.getByRole('button', { name: 'View version 1', exact: true }).waitFor()
    const manual = firstBody + '\n用户手动编辑'
    await editor.dispatchEvent('compositionstart', { data: '用户' })
    await editor.fill(manual)
    await page.waitForTimeout(1100)
    const projects = await fixture.rpc<{ readonly items: readonly { readonly id: string }[] }>(cookies, 'projectsList', { limit: 1 })
    const whileComposing = await fixture.rpc<{ readonly draft: { readonly body: string } }>(cookies, 'projectsOpen', { projectId: projects.items[0]!.id })
    expect(whileComposing.draft.body).toBe(firstBody)
    await editor.dispatchEvent('compositionend', { data: '用户手动编辑' })
    await expect.poll(async () => (await panel.getByRole('status', { name: 'Draft synchronization status' }).innerText()).startsWith('Synced to server')).toBe(true)
    fixture.upstream.script.push(contentReply(manual + '（保留）', [sources[0]!.versionId]))
    await instruction.fill('保留用户手动编辑，只做简短修改。')
    await panel.getByRole('button', { name: 'Revise full draft', exact: true }).click()
    await expect.poll(() => editor.inputValue(), { timeout: 15_000 }).toBe(manual + '（保留）')
    expect(JSON.stringify(fixture.upstream.requests.at(-1))).toContain('用户手动编辑')
    await editor.focus()
    await editor.evaluate((element) => {
      if (!(element instanceof HTMLTextAreaElement)) throw new Error('Draft editor is not a text area')
      const start = element.value.indexOf('只改这里')
      element.setSelectionRange(start, start + '只改这里'.length)
      document.dispatchEvent(new Event('selectionchange', { bubbles: true }))
    })
    await panel.getByText('Selection ready. Text outside this range will be preserved exactly.').waitFor()
    fixture.upstream.script.push(contentReply('新的选区✨', [sources[0]!.versionId]))
    await instruction.fill('只替换选区。')
    await panel.getByRole('button', { name: 'Revise selection only', exact: true }).click()
    const selectedBody = (manual + '（保留）').replace('只改这里', '新的选区✨')
    await expect.poll(() => editor.inputValue(), { timeout: 15_000 }).toBe(selectedBody)
    await panel.getByRole('button', { name: 'Save version', exact: true }).click()
    await panel.getByRole('button', { name: 'View version 2', exact: true }).waitFor()
    await panel.getByRole('button', { name: 'View version 1', exact: true }).click()
    const preview = panel.getByRole('textbox', { name: 'Historical version text (read only)', exact: true })
    await expect.poll(() => preview.inputValue()).toBe(firstBody)
    expect(await editor.inputValue()).toBe(selectedBody)
    await panel.getByRole('button', { name: 'Restore this version as draft', exact: true }).click()
    await expect.poll(() => editor.inputValue()).toBe(firstBody)
    await panel.getByRole('button', { name: 'Save version', exact: true }).click()
    await panel.getByRole('button', { name: 'View version 3', exact: true }).waitFor()
    for (const name of ['Export server draft', 'Export viewed version']) {
      const event = page.waitForEvent('download')
      await panel.getByRole('button', { name, exact: true }).click()
      const file = await (await event).path()
      expect(file).not.toBeNull(); if (file) expect(readFileSync(file, 'utf8')).toBe(firstBody)
    }
    await page.reload()
    await panel.getByRole('button', { name: 'Browser spoken project', exact: true }).click()
    await expect.poll(() => editor.inputValue()).toBe(firstBody)
    await panel.evaluate((element) => { element.scrollTop = 0 })
    await page.screenshot({ path: join(proof, 'employee-desktop.png'), fullPage: true })
    await page.setViewportSize({ width: 375, height: 812 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await panel.evaluate((element) => { element.scrollTop = 0 })
    await page.screenshot({ path: join(proof, 'employee-375.png'), fullPage: true })
    const secondWindow = await context.newPage()
    await secondWindow.goto(fixture.origin)
    const secondPanel = secondWindow.getByRole('region', { name: 'Writing workspace', exact: true })
    await secondPanel.getByText('My profile and sources', { exact: true }).click()
    await secondPanel.getByRole('button', { name: 'Revoke authorization', exact: true }).click()
    await expect.poll(() => editor.inputValue()).toBe('')
    expect(await panel.getByRole('button', { name: 'Export server draft', exact: true }).isDisabled()).toBe(true)
    await secondWindow.close()
    await panel.getByRole('button', { name: 'View version 1', exact: true }).click()
    await expect.poll(() => preview.inputValue()).toBe('')
    expect(await panel.getByRole('button', { name: 'Restore this version as draft', exact: true }).isDisabled()).toBe(true)
    expect(await panel.getByRole('button', { name: 'Export viewed version', exact: true }).isDisabled()).toBe(true)
    await panel.getByRole('button', { name: 'Start fresh in this project', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm clearing the current draft', exact: true }).click()
    await expect.poll(() => editor.isEnabled()).toBe(true)
    fixture.upstream.script.push(contentReply('基于当前画像的新合成内容'))
    await instruction.fill('基于当前画像重新开始，不使用已撤销的资料。')
    await panel.getByRole('button', { name: 'Generate draft', exact: true }).click()
    await expect.poll(() => editor.inputValue(), { timeout: 15_000 }).toBe('基于当前画像的新合成内容')
    expect(JSON.stringify(fixture.upstream.requests.at(-1))).not.toContain('先问学生')
    await panel.getByRole('button', { name: 'Sign out', exact: true }).click()
    await panel.getByLabel('Username', { exact: true }).fill('employee-b')
    await panel.getByLabel('Password', { exact: true }).fill(PASSWORD)
    await panel.getByRole('button', { name: 'Sign in', exact: true }).click()
    await panel.getByText('No projects yet. Create a project to begin.', { exact: true }).waitFor()
    expect(await panel.getByText('Browser spoken project', { exact: true }).count()).toBe(0)
    expect(await panel.textContent()).not.toContain('用户手动编辑')
    expect(await page.evaluate(() => Object.values(localStorage).some(value => /用户手动编辑|课堂观察/.test(String(value))))).toBe(false)
    expect(errors).toEqual([])
  } catch (error) {
    if (browser) { const page = browser.contexts()[0]?.pages()[0]; await page?.screenshot({ path: join(proof, 'employee-failure.png'), fullPage: true }).catch(() => {}); writeFileSync(join(proof, 'employee-failure.json'), JSON.stringify({ errors, body: await page?.locator('body').innerText() }, null, 2)) }
    throw error
  } finally { await browser?.close(); await fixture.dispose() }
}, 150_000)
